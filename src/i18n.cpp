const char* tr(const char* en) {
    if (g_lang == L_EN) return en;
    const auto& m = g_lang == L_JA ? ja() : g_lang == L_KO ? ko() : zh();
    auto it = m.find(en);
    return it == m.end() ? en : it->second;
}

void set_lang(Lang l) { g_lang = l; }
Lang get_lang() { return g_lang; }

Lang lang_from_code(const char* code) {
    if (code && (strncmp(code, "zh", 2) == 0)) return L_ZH_CN;
    if (code && (strncmp(code, "ja", 2) == 0)) return L_JA;
    if (code && (strncmp(code, "ko", 2) == 0)) return L_KO;
    return L_EN;
}
